"""Run analytics/sql/phantom_queries.sql against the database and write analytics/SQL_RESULTS.md.

Each block in the .sql file starts with `-- name: <id>` and a one-line business question.
The report shows the question, the SQL and the result table, so a reviewer can check both.

    python -m app.phantom.sql_report
"""

from __future__ import annotations

import re
from datetime import datetime, timezone
from pathlib import Path
from typing import List, Tuple

from sqlalchemy import text

from app.database import engine
from app.phantom.export import ANALYTICS, ROOT

SQL_FILE = ANALYTICS / "sql" / "phantom_queries.sql"


def parse_queries(sql: str) -> List[Tuple[str, str, str]]:
    """→ [(name, question, sql)] from `-- name:` blocks."""
    out = []
    for block in re.split(r"^-- name:\s*", sql, flags=re.M)[1:]:
        lines = block.strip().splitlines()
        name = lines[0].strip()
        question = lines[1].lstrip("- ").strip() if len(lines) > 1 and lines[1].startswith("--") else ""
        body = "\n".join(lines[2:] if question else lines[1:]).strip().rstrip(";")
        out.append((name, question, body))
    return out


def run(conn, query: str) -> Tuple[List[str], List[tuple]]:
    res = conn.execute(text(query))
    return list(res.keys()), [tuple(r) for r in res.fetchall()]


def _cell(v) -> str:
    if v is None:
        return "—"
    if isinstance(v, float):
        return f"{v:,.1f}" if not v.is_integer() else f"{int(v):,}"
    return str(v).replace("|", "/")


def md_table(cols: List[str], rows: List[tuple]) -> str:
    if not rows:
        return "_(no rows)_"
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(_cell(v) for v in r) + " |" for r in rows]
    return "\n".join(lines)


def main(path: Path = SQL_FILE) -> Path:
    queries = parse_queries(path.read_text(encoding="utf-8"))
    parts = ["# Phantom Hunter — SQL analytics",
             "",
             f"Generated by `python -m app.phantom.sql_report` on {datetime.now(timezone.utc):%Y-%m-%d} from "
             f"[`{path.relative_to(ROOT).as_posix()}`](sql/phantom_queries.sql). Each section: the business question, the SQL, the live result.",
             ""]
    parts += [f"- [{q or n}](#{n.replace('_', '-')})" for n, q, _ in queries] + [""]
    with engine.connect() as conn:
        for name, question, sql in queries:
            cols, rows = run(conn, sql)
            parts += [f"## {name.replace('_', '-')}", "", f"**{question}**", "", "```sql", sql, "```", "", md_table(cols, rows), ""]
    out = ANALYTICS / "SQL_RESULTS.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    print(f"ran {len(queries)} queries → {out.relative_to(ROOT)}")
    return out


if __name__ == "__main__":
    main()
